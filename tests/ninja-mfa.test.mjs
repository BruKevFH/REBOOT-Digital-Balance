import test from 'node:test';
import assert from 'node:assert/strict';
import {createNinjaStore} from '../server/ninja-store.mjs';
import {createNinjaAuth} from '../server/ninja-auth.mjs';
import {testMfaCode} from '../server/ninja-mfa.mjs';
const password='Secret Ninja Passphrase 2026';
const mfaKey='12'.repeat(32);
function fixture(t,key=mfaKey){
 let tick=1711111110000;const now=()=>tick,store=createNinjaStore({now});
 t.after(()=>store.close());
 const auth=createNinjaAuth(store,{now,mfaKey:key});
 return {store,auth,now,advance:ms=>{tick+=ms;}};
}
const code=(setup,now)=>testMfaCode(setup.secret,Math.floor(now()/30000));
test('MFA setup is encrypted, requires password and is enabled only after a real TOTP',async t=>{
 const {auth,store,now}=fixture(t),user=await auth.register({username:'Mfa Ninja',password});
 const wrong=auth.mfa.setup(user.user.id,{password:'wrong'});
 await assert.rejects(wrong,e=>e.code==='PASSWORD_CONFIRMATION_FAILED');
 const start=await auth.mfa.setup(user.user.id,{password});
 assert.match(start.secret,/^[A-Z2-7]{32}$/);
 assert(start.otpauthUri.startsWith('otpauth://totp/'));
 const raw=store.db.prepare('SELECT * FROM ninja_mfa WHERE user_id=?').get(user.user.id);
 assert(!JSON.stringify(raw).includes(start.secret));
 assert.equal((await auth.mfa.status(user.user.id)).enabled,false);
 await assert.rejects(auth.mfa.confirm(user.user.id,{code:'111111'}),e=>e.code==='MFA_INVALID');
 const confirmed=await auth.mfa.confirm(user.user.id,{code:code(start,now)});
 assert.equal(confirmed.enabled,true);
 assert.equal(confirmed.recoveryCodes.length,10);
 assert(confirmed.recoveryCodes.every(v=>/^NNM-[A-Za-z0-9_-]{27}$/.test(v)));
 const after=store.db.prepare('SELECT * FROM ninja_mfa WHERE user_id=?').get(user.user.id);
 for(const secret of [start.secret,...confirmed.recoveryCodes])assert(!JSON.stringify(after).includes(secret));
});
test('login requires MFA before session and rejects replays and invalid challenges',async t=>{
 const {auth,store,advance,now}=fixture(t),user=await auth.register({username:'Mfa Login',password});
 const start=await auth.mfa.setup(user.user.id,{password});
 await auth.mfa.confirm(user.user.id,{code:code(start,now)});
 advance(31000);
 const pending=await auth.login({username:'Mfa Login',password});
 assert.equal(pending.mfaRequired,true);
 assert.equal(pending.token,undefined);
 assert.equal(pending.user,undefined);
 assert.throws(()=>auth.authenticate(pending.challenge),e=>e.code==='UNAUTHENTICATED');
 const bad=await auth.mfa.finishLogin({challenge:pending.challenge,code:'999999'}).catch(e=>e);
 assert.equal(bad.code,'MFA_INVALID');
 const completed=await auth.mfa.finishLogin({challenge:pending.challenge,code:code(start,now)});
 assert.equal(completed.user.id,user.user.id);
 assert.match(completed.token,/^[A-Za-z0-9_-]{43}$/);
 assert.equal(auth.authenticate(completed.token).id,user.user.id);
 await assert.rejects(auth.mfa.finishLogin({challenge:pending.challenge,code:code(start,now)}),e=>e.code==='MFA_INVALID');
 const second=await auth.login({username:'Mfa Login',password});
 await assert.rejects(auth.mfa.finishLogin({challenge:second.challenge,code:code(start,now)}),e=>e.code==='MFA_INVALID');
 assert.equal(store.db.prepare('SELECT enabled FROM ninja_mfa WHERE user_id=?').get(user.user.id).enabled,1);
});
test('invalid MFA attempts are committed and locked after 5 guesses',async t=>{
 const {auth,now}=fixture(t),user=await auth.register({username:'Mfa Brute',password});
 const start=await auth.mfa.setup(user.user.id,{password});
 await auth.mfa.confirm(user.user.id,{code:code(start,now)});
 const pending=await auth.login({username:'Mfa Brute',password});
 for(let i=0;i<5;i++)await assert.rejects(auth.mfa.finishLogin({challenge:pending.challenge,code:'invalid'}),e=>e.code==='MFA_INVALID');
 await assert.rejects(auth.mfa.finishLogin({challenge:pending.challenge,code:code(start,now)}),e=>e.code==='MFA_INVALID');
});
test('recovery codes work exactly once and MFA required on password reset',async t=>{
 const {auth,now,advance}=fixture(t),user=await auth.register({username:'Mfa Recover',password});
 const start=await auth.mfa.setup(user.user.id,{password});
 const confirmed=await auth.mfa.confirm(user.user.id,{code:code(start,now)});
 const nextPassword='Another Strong Password 2027';
 await assert.rejects(auth.resetPassword({username:'Mfa Recover',recoveryKey:user.recoveryKey,password:nextPassword}),e=>e.code==='MFA_REQUIRED');
 advance(31000);
 const reset=await auth.resetPassword({username:'Mfa Recover',recoveryKey:user.recoveryKey,password:nextPassword,mfaCode:confirmed.recoveryCodes[0]});
 assert.equal(reset.user.id,user.user.id);
 assert.match(reset.recoveryKey,/^NNR-/);
 const pending=await auth.login({username:'Mfa Recover',password:nextPassword});
 assert.equal(pending.mfaRequired,true);
 const result=await auth.mfa.finishLogin({challenge:pending.challenge,code:confirmed.recoveryCodes[1]});
 assert.equal(result.user.id,user.user.id);
 await assert.rejects(auth.mfa.finishLogin({challenge:(await auth.login({username:'Mfa Recover',password:nextPassword})).challenge,code:confirmed.recoveryCodes[1]}),e=>e.code==='MFA_INVALID');
 await assert.rejects(auth.mfa.disable(user.user.id,{password:nextPassword,code:'111111'}),e=>e.code==='MFA_INVALID');
 const disabled=await auth.mfa.disable(user.user.id,{password:nextPassword,code:confirmed.recoveryCodes[2]});
 assert.equal(disabled.enabled,false);
 const login=await auth.login({username:'Mfa Recover',password:nextPassword});
 assert(login.token);
});
test('missing encryption key fails closed for MFA accounts',async t=>{
 const {auth,now,store}=fixture(t),user=await auth.register({username:'Mfa Failsafe',password});
 const start=await auth.mfa.setup(user.user.id,{password});
 await auth.mfa.confirm(user.user.id,{code:code(start,now)});
 const noKey=createNinjaAuth(store,{now,mfaKey:null});
 assert.equal((await noKey.mfa.status(user.user.id)).enabled,true);
 assert.equal((await noKey.mfa.status(user.user.id)).available,false);
 await assert.rejects(noKey.login({username:'Mfa Failsafe',password}),e=>e.code==='MFA_UNAVAILABLE');
 await assert.rejects(noKey.mfa.setup(user.user.id,{password}),e=>e.code==='MFA_UNAVAILABLE');
});
